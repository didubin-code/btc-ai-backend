import argparse, json, math, os


def cp_upper(k, n, conf=0.95):
    if n == 0:
        return 1.0
    lo, hi = 0.0, 1.0
    for _ in range(200):
        m = (lo + hi) / 2
        c = sum(math.exp(math.lgamma(n + 1) - math.lgamma(i + 1) - math.lgamma(n - i + 1) + i * math.log(m) + (n - i) * math.log1p(-m)) for i in range(k + 1))
        lo, hi = (lo, m) if c <= 1 - conf else (m, hi)
    return (lo + hi) / 2


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def pct(x, d=3):
    return ('%.' + str(d) + 'f %%') % x


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    D = a.data
    L = []
    w = L.append
    w('# Result tables (generated by `pipeline/final_tables.py` from the result files; do not edit by hand)\n')
    # 1. contract replays: pre-registered splits (decisive.py)
    dv = load(os.path.join(D, 'decisive.json'))
    labels = {'r281_usdc': '2.8.1 (pre-registered build), BTCUSDC feed: PRIMARY', 'r28_usdc': '2.8 (deployed), BTCUSDC feed',
              'r281_usdt': '2.8.1, BTCUSDT feed (robustness)', 'cand_usdc': 'candidate ADAPTIVE_BASIS=1, BTCUSDC feed (exploratory: designed after seeing U2 calibration)',
              'cand_usdt': 'candidate ADAPTIVE_BASIS=1, BTCUSDT feed (exploratory)'}
    if dv:
        w('\n## LOCKED reliability on real Kalshi contracts, by pre-registered split\n')
        w('U = U1 + U2 is decisive (never used for fitting). "Seen" = Jul 22 – Oct 13 (S1 + S2 + S0), used during development: reported, not decisive. '
          'Cells "k / n (u)": wrong / LOCKED at that time, and the one-sided 95 %% upper bound u in %%. Break-even at 99.9 ¢ is 0.093 %%.\n')
        for run, lab in labels.items():
            if run not in dv:
                continue
            w('\n### %s\n' % lab)
            w('| Split | Windows | LOCKED at some point | First-LOCKED wrong | Rate (95 % CI) | T−60 | T−30 | T−20 | T−15 | T−10 | T−5 |')
            w('|---|---|---|---|---|---|---|---|---|---|---|')
            for sp, v in dv[run].items():
                fl, fx = v['firstLocked'], v['fixed']
                c = lambda T: '%d / %d (%.3f)' % (fx[T]['k'], fx[T]['n'], fx[T]['upper95OneSidedPct'])
                w('| %s | %d | %.1f %% | %d / %d | %s (%s–%s) | %s | %s | %s | %s | %s | %s |' % (sp, v['windows'], v['coveragePct'], fl['k'], fl['n'], pct(fl['ratePct']),
                  pct(fl['ci95Pct'][0]), pct(fl['ci95Pct'][1]), c('60'), c('30'), c('20'), c('15'), c('10'), c('5')))
        pr = dv['prereg']
        r1, r2 = pr['rule1_E20_upper95_below_break_even'], pr['rule2_volume_50k_in_half_of_E20']
        w('\n### Pre-registered verdict rules for $50,000 at 99.9 ¢ (primary engine, U)\n')
        w('| Rule | Needed | Observed | Result |')
        w('|---|---|---|---|')
        w('| YES-1: E20 one-sided 95 %% upper bound | < %.3f %% | %d / %d wrong, bound %.4f %% | %s |' % (r1['breakEvenPct'], r1['k'], r1['n'], r1['upper95OneSidedPct'], 'pass' if r1['pass'] else 'fail'))
        w('| YES-2: ≥ 50,046 contracts at ≤ 99.9 ¢ within 12 s | in ≥ 50 %% of E20 entries | %d of %d (%.4f %%) | %s |' % (r2['withAtLeast50046'], r2['entriesWithTape'], r2['sharePct'], 'pass' if r2['pass'] else 'fail'))
        w('| YES-3: no E20 failure a reasonable trader could not avoid | none | %s | %s |' % ('; '.join('%s %s, margin $%.2f, called side last traded at %s ¢%s' % (f['ticker'], f['side'], f['marginUsd'], f['lastCalledSidePriceCents'], ' (90 ¢ guard blocks)' if f['guardBlocks'] else ' (guard passes)') for f in pr['rule3_E20_failures_on_U']),
          'fail' if any(not f['guardBlocks'] for f in pr['rule3_E20_failures_on_U']) else 'pass'))
        w('| NO-a: E20 two-sided CI wholly above break-even | — | %s | %s |' % ('yes' if pr['NO_if_CI_wholly_above'] else 'no', 'triggers NO' if pr['NO_if_CI_wholly_above'] else 'not triggered'))
        w('| NO-b: 50,046 contracts in < 10 %% of E20 entries | — | %.4f %% | %s |' % (r2['sharePct'], 'triggers NO' if pr['NO_if_volume_below_10pct'] else 'not triggered'))
    # 1b. supplementary analyses (supplement.py)
    sp = load(os.path.join(D, 'supplement.json'))
    if sp:
        w('\n### Pre-registered verdict rules at other sizes and prices (U2 E20 entries with a tape)\n')
        w('| Price | Contracts | Break-even | Entries with that volume in 12 s | YES-1 | YES-2 | NO-b | Verdict |')
        w('|---|---|---|---|---|---|---|---|')
        for r in sp['9_preregRulesBySizePrice']['rows']:
            w('| %.1f ¢ | %d | %.3f %% | %.3f %% | %s | %s | %s | %s |' % (r['price'], r['contracts'], r['breakEvenPct'], r['volumeSharePct'], r['YES1'], r['YES2'], r['NOb'], r['verdict']))
        c = sp['1_failureClasses']
        w('\n### Wrong first-LOCKED calls by what the replay feed showed\n')
        w('| Split | Wrong | Feed also ended on the other side (real reversal) | Basis-decided | Real reversals passing buffer + guard with the market ≥ 90 ¢ |')
        w('|---|---|---|---|---|')
        for k, v in c.items():
            w('| %s | %d | %d (DOWN %s, UP %s) | %d | %d (%.3f %% of calls) |' % (k, v['wrong'], v['realReversal_feedThroughStrike'], v['real_bySide'].get('DOWN', 0), v['real_bySide'].get('UP', 0), v['basisDecided'], len(v['real_notBlocked_marketAgreeing']), v['realNotBlockedRatePct']))
        w('\n### Predictors at the first LOCKED second (U)\n')
        for name, key in (('Required move ($)', 'requiredMoveUsd'), ('Prior adverse excursion, 60 s (σ)', 'priorAdverseExcursion60s_sigma'), ('Volatility change (last 60 s / previous 240 s)', 'volChange_last60_vs_prev240'), ('Engine volatility bucket', 'engineVolBucket')):
            w('* %s: ' % name + '; '.join('%s %d/%d' % (b_, x['k'], x['n']) for b_, x in sp['2_predictors_U'][key].items()))
        for fn, lab in (('volchange_seen', 'seen'), ('volchange_proxy', 'proxy')):
            v = load(os.path.join(D, fn + '.json'))
            if v:
                w('* Volatility-jump rule (ratio ≥ 2) out of sample, %s: flagged %d/%d, rest %d/%d, Fisher p = %s' % (lab, v['jump'][0], v['jump'][1], v['rest'][0], v['rest'][1], v['fisherP']))
        bb = sp['3_dayBlockBootstrap_U']
        w('\nDay-block bootstrap (U): first LOCKED %s %%; T−20 upper %s %%.' % ('–'.join(str(x) for x in bb['firstLocked_ci95_and_upper95'][:2]), bb['T20_ci95_and_upper95'][2]))
    # 2. trading (trading_eval.py, corrected baseline)
    def trading_table(t, label, note=''):
        w('\n## %s\n' % label)
        P = t['_params']
        w('Fill rule: an order of C contracts fills only if other takers bought ≥ C contracts of that side at ≤ 99.9 ¢ in the 12 s after the entry (market baseline: strictly after the trigger print), '
          'plus %g s latency; price = their VWAP (or the worst of them), plus Kalshi\'s taker fee. 95 %% CI: day-level block bootstrap. Markets in period %d, with a Kalshi tape %d.%s\n' % (P.get('latencySec', 0), P.get('marketsInPeriod', 0), P.get('marketsWithTape', 0), note))
        w('| Strategy | C | Trades | Lost | Mean ¢/contract (VWAP) | 95 % CI | Mean at worst fill | Total |')
        w('|---|---|---|---|---|---|---|---|')
        for k in sorted(x for x in t if not x.startswith('_')):
            for C in (10, 100, 1000, 10000, 50046):
                x, y = t[k].get('C%d_vwap' % C), t[k].get('C%d_worst' % C)
                if not x:
                    continue
                w('| %s | %d | %d | %d | %+.3f | %s | %s | $%s |' % (k, C, x['trades'], x['lost'], x['meanCentsPerContract'], ' to '.join('%+.3f' % q for q in x['ci95BootDays']),
                                                               ('%+.3f' % y['meanCentsPerContract']) if y else '—', format(round(x['totalUsd']), ',')))
        if t.get('_paired'):
            w('\nPaired difference (same days resampled), ¢ per contract:\n')
            w('| Comparison | Difference | 95 % CI |')
            w('|---|---|---|')
            for k, v in t['_paired'].items():
                if v:
                    w('| %s | %+.3f | %+.3f to %+.3f |' % (k, v['diff'], v['ci95BootDays'][0], v['ci95BootDays'][1]))
    t = load(os.path.join(D, 'trading2_U2_L0.json'))
    if t:
        trading_table(t, 'Trading at realistic sizes, unseen period U2 (Jan 13 – Jul 21): unseen data, EXPLORATORY strategy definitions (not pre-registered), optimistic fill model')
    lat = [(lt, load(os.path.join(D, "trading2_U2_L%d.json" % lt))) for lt in (0, 2, 5)] + [('15 s buffer, 0', load(os.path.join(D, 'trading2_U2_L0_buf15.json'))), ('15 s buffer, 12', load(os.path.join(D, 'trading2_U2_L12_buf15.json')))]
    lat = [(lt, x) for lt, x in lat if x]
    if lat:
        w('\n### Entry latency sensitivity (U2, C = 100, VWAP)\n')
        w('| Latency | model:first | model:first+edge | model:T20 | market:99 | market:99.5 |')
        w('|---|---|---|---|---|---|')
        for lt, x in lat:
            cell = lambda k: ('%+.3f (%d trades)' % (x[k]['C100_vwap']['meanCentsPerContract'], x[k]['C100_vwap']['trades'])) if x.get(k, {}).get('C100_vwap') else '—'
            w('| %s s | %s | %s | %s | %s | %s |' % (lt, cell('model:first'), cell('model:first+edge'), cell('model:T20'), cell('market:99'), cell('market:99.5')))
    t = load(os.path.join(D, 'trading2_full_L0.json'))
    if t:
        w('\n### By month, C = 100, VWAP (all periods with a tape)\n')
        ks = [k for k in ('model:first', 'model:T20', 'market:99', 'market:99.5') if t.get(k, {}).get('C100_vwap', {}).get('byMonth')]
        months = sorted(set(m for k in ks for m in t[k]['C100_vwap']['byMonth']))
        w('| Month | ' + ' | '.join(ks) + ' |')
        w('|---' * (len(ks) + 1) + '|')
        for m in months:
            w('| %s | ' % m + ' | '.join(('%+.3f ¢, %d trades, %d lost' % (lambda b: (b['meanCentsPerContract'], b['trades'], b['lost']))(t[k]['C100_vwap']['byMonth'][m])) if m in t[k]['C100_vwap']['byMonth'] else '—' for k in ks) + ' |')
    t = load(os.path.join(D, 'trading2_seen_L0.json'))
    if t:
        trading_table(t, 'Trading, Jul 22 – Oct 16 (seen period plus U1 dates; U1 has no tapes): reported, not decisive, PARTIAL tape coverage', ' The tape download for this period was incomplete when this table was built.')
    for name, lab in (('trading2_cand_U2_L0', 'Trading, candidate ADAPTIVE_BASIS=1, U2 (exploratory)'),):
        t = load(os.path.join(D, name + '.json'))
        if t:
            trading_table(t, lab)
    for C in (100, 1000):
        x = load(os.path.join(D, 'exit_full_C%d.json' % C))
        if x:
            if C == 100:
                w('\n## Exit on REVERSAL WARNING vs hold (first-LOCKED entries that filled)\n')
                w('| C | Entries | Warned later | of which lost | of which won | Exited (enough prints) | Hold: mean ¢ | Exit rule: mean ¢ | Hold total | Exit total |')
                w('|---|---|---|---|---|---|---|---|---|---|')
            w('| %d | %d | %d | %d | %d | %d | %+.3f | %+.3f | $%s | $%s |' % (C, x['entries'], x['warned'], x['warnedLost'], x['warnedWon'], x['exitedWithFills'], x['holdMean'], x['exitMean'], format(round(x['holdUsd']), ','), format(round(x['exitUsd']), ',')))
    # 3. execution capacity
    e = load(os.path.join(D, 'exec_r281_full.json'))
    if e:
        P = e['params']
        w('\n## Executable volume (contracts of the called side bought by takers at ≤ %.1f ¢ within %g s of the entry)\n' % (P['limitCents'], P['orderSec']))
        w('| Entry | Entries with Kalshi prints | Median | 90th pct | 99th pct | Entries with ≥ %s contracts (your $%s) |' % (format(P['contractsForBudget'], ','), format(int(P['budgetUsd']), ',')))
        w('|---|---|---|---|---|---|')
        for k, v in e['rules'].items():
            c = v['contractsInOrderTime']
            w('| %s | %d | %s | %s | %s | %s |' % (k, v['withTape'], c['0.5'], c['0.9'], c['0.99'], pct(100 * (v['shareWithAtLeastBudgetContracts'] or 0), 3)))
    # 4. proxy study
    pr = load(os.path.join(D, 'summary_r281_proxy27m.json'))
    if pr:
        v = pr['all']
        fl, ft = v['firstLocked'], v['fixedTime']
        w('\n## Long-horizon PROXY study (Binance BTCUSDT 1 s, Oct 2023 – Jan 2026; outcomes defined by the proxy, not Kalshi)\n')
        w('| Windows | LOCKED at some point | First-LOCKED wrong | Rate (95 % CI) | Still LOCKED at T−30 | T−20 | T−15 | T−10 |')
        w('|---|---|---|---|---|---|---|---|')
        w('| %d | %.1f %% | %d / %d | %s (%s–%s) | %d / %d | %d / %d | %d / %d | %d / %d |' % (v['windows'], v['coveragePct'], fl['k'], fl['n'], pct(fl['ratePct']), pct(fl['ci95Pct'][0]), pct(fl['ci95Pct'][1]),
                                                                                ft['30']['k'], ft['30']['n'], ft['20']['k'], ft['20']['n'], ft['15']['k'], ft['15']['n'], ft['10']['k'], ft['10']['n']))
        w('\nBy month (first-LOCKED wrong / calls):\n')
        w(', '.join('%s %d/%d' % (m, x['k'], x['n']) for m, x in v['byMonth'].items()))
    # 5. basis
    b = load(os.path.join(D, 'basis_all.json'))
    if b:
        w('\n## How closely each 1 Hz feed tracks Kalshi\'s official settlement average\n')
        w('| Feed | Windows | Mean level ($) | One-step error sd of the server\'s basis predictor ($) | |error| > $10 | |error| > $20 | Period |')
        w('|---|---|---|---|---|---|---|')
        names = {'proxy': 'Binance BTCUSDT', 'usdc': 'Binance BTCUSDC', 'cb': 'Coinbase BTC-USD trades', 'kr': 'Kraken XBT/USD trades'}
        for k, v in b.items():
            if v:
                w('| %s | %d | %.2f | %.2f | %s | %s | %s – %s |' % (names.get(k, k), v['windows'], v['meanLevel'], v['oneStepErrSd'], pct(100 * v['shareAbsErrOver10'], 2), pct(100 * v['shareAbsErrOver20'], 2), v['from'][:10], v['to'][:10]))
    open(a.out, 'w').write('\n'.join(L) + '\n')
    print('written', a.out, len(L), 'lines')


if __name__ == '__main__':
    main()
