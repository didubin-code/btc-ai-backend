"""Builds the result tables of VALIDATION_REPORT.md directly from the result files (no number is typed by hand).
  python3 final_tables.py --data /home/user/data_val --out ../RESULTS_TABLES.md"""
import argparse, json, math, os


def cp_upper(k, n, conf=0.95):
    if n == 0:
        return 1.0
    lo, hi = 0.0, 1.0
    for _ in range(200):
        m = (lo + hi) / 2
        c = sum(math.exp(math.lgamma(n + 1) - math.lgamma(i + 1) - math.lgamma(n - i + 1) + i * math.log(m) + (n - i) * math.log1p(-m)) for i in range(k + 1))
        lo, hi = (lo, m) if c <= 1 - conf else (m, hi)
    return (lo + hi) / 2


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def pct(x, d=3):
    return ('%.' + str(d) + 'f %%') % x


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    D = a.data
    L = []
    w = L.append
    w('# Result tables (generated by `pipeline/final_tables.py` from the result files; do not edit by hand)\n')
    # 1. contract replays by split
    for name, label in [('summary_r281_usdc', '2.8.1, BTCUSDC feed (primary)'), ('summary_r28_usdc', '2.8 (deployed), BTCUSDC feed'),
                        ('summary_r281_usdt', '2.8.1, BTCUSDT feed (robustness)'), ('summary_cand_usdc', 'candidate ADAPTIVE_BASIS=1, BTCUSDC feed'),
                        ('summary_cand_usdt', 'candidate ADAPTIVE_BASIS=1, BTCUSDT feed')]:
        d = load(os.path.join(D, name + '.json'))
        if not d:
            continue
        w('\n## %s\n' % label)
        w('| Split | Windows | LOCKED at some point | First-LOCKED wrong | Rate (95 %% CI) | Still LOCKED at T−30 | T−20 | T−15 | T−10 | T−5 |')
        w('|---|---|---|---|---|---|---|---|---|---|')
        for k in ['all', 'U2_unseen_before', 'S1_holdout_seen', 'S2_train_gap', 'S0_dev_insample', 'U1_unseen_after']:
            v = d.get(k)
            if not v or not v.get('firstLocked'):
                continue
            fl, ft = v['firstLocked'], v['fixedTime']
            cell = lambda T: ('%d / %d' % (ft[T]['k'], ft[T]['n'])) if ft.get(T) else '—'
            w('| %s | %d | %.1f %% | %d / %d | %s (%s–%s) | %s | %s | %s | %s | %s |' % (k, v['windows'], v['coveragePct'], fl['k'], fl['n'], pct(fl['ratePct']), pct(fl['ci95Pct'][0]), pct(fl['ci95Pct'][1]),
                                                                              cell('30'), cell('20'), cell('15'), cell('10'), cell('5')))
    # 2. trading
    for name, label in [('trading_full', 'Trading at realistic sizes, all windows with Kalshi prints'), ('trading_U2', 'Trading, unseen period Jan 13 – Jul 21 only')]:
        t = load(os.path.join(D, name + '.json'))
        if not t:
            continue
        w('\n## %s\n' % label)
        w('Fill rule: an order of C contracts fills only if other takers bought ≥ C contracts of that side at ≤ 99.9 ¢ within 12 s; price = their VWAP (or the worst of them), plus Kalshi\'s taker fee. 95 % CI: day-level block bootstrap.\n')
        w('| Strategy | C | Trades | Lost | Mean ¢/contract (VWAP) | 95 % CI | Mean at worst fill | Total |')
        w('|---|---|---|---|---|---|---|---|')
        for k in sorted(x for x in t if not x.startswith('_')):
            for C in (10, 100, 1000, 10000):
                x, y = t[k].get('C%d_vwap' % C), t[k].get('C%d_worst' % C)
                if not x:
                    continue
                w('| %s | %d | %d | %d | %+.3f | %s | %s | $%s |' % (k, C, x['trades'], x['lost'], x['meanCentsPerContract'], ' to '.join('%+.3f' % q for q in x['ci95BootDays']),
                                                               ('%+.3f' % y['meanCentsPerContract']) if y else '—', format(round(x['totalUsd']), ',')))
    # 3. execution capacity
    e = load(os.path.join(D, 'exec_r281_full.json'))
    if e:
        P = e['params']
        w('\n## Executable volume (contracts of the called side bought by takers at ≤ %.1f ¢ within %g s of the entry)\n' % (P['limitCents'], P['orderSec']))
        w('| Entry | Entries with Kalshi prints | Median | 90th pct | 99th pct | Entries with ≥ %s contracts (your $%s) |' % (format(P['contractsForBudget'], ','), format(int(P['budgetUsd']), ',')))
        w('|---|---|---|---|---|---|')
        for k, v in e['rules'].items():
            c = v['contractsInOrderTime']
            w('| %s | %d | %s | %s | %s | %s |' % (k, v['withTape'], c['0.5'], c['0.9'], c['0.99'], pct(100 * (v['shareWithAtLeastBudgetContracts'] or 0), 3)))
    # 4. proxy study
    pr = load(os.path.join(D, 'summary_r281_proxy27m.json'))
    if pr:
        v = pr['all']
        fl, ft = v['firstLocked'], v['fixedTime']
        w('\n## Long-horizon PROXY study (Binance BTCUSDT 1 s, Oct 2023 – Jan 2026; outcomes defined by the proxy, not Kalshi)\n')
        w('| Windows | LOCKED at some point | First-LOCKED wrong | Rate (95 % CI) | Still LOCKED at T−30 | T−20 | T−15 | T−10 |')
        w('|---|---|---|---|---|---|---|---|')
        w('| %d | %.1f %% | %d / %d | %s (%s–%s) | %d / %d | %d / %d | %d / %d | %d / %d |' % (v['windows'], v['coveragePct'], fl['k'], fl['n'], pct(fl['ratePct']), pct(fl['ci95Pct'][0]), pct(fl['ci95Pct'][1]),
                                                                                ft['30']['k'], ft['30']['n'], ft['20']['k'], ft['20']['n'], ft['15']['k'], ft['15']['n'], ft['10']['k'], ft['10']['n']))
        w('\nBy month (first-LOCKED wrong / calls):\n')
        w(', '.join('%s %d/%d' % (m, x['k'], x['n']) for m, x in v['byMonth'].items()))
    # 5. basis
    b = load(os.path.join(D, 'basis_all.json'))
    if b:
        w('\n## How closely each 1 Hz feed tracks Kalshi\'s official settlement average\n')
        w('| Feed | Windows | Mean level ($) | One-step error sd of the server\'s basis predictor ($) | |error| > $10 | |error| > $20 | Period |')
        w('|---|---|---|---|---|---|---|')
        names = {'proxy': 'Binance BTCUSDT', 'usdc': 'Binance BTCUSDC', 'cb': 'Coinbase BTC-USD trades', 'kr': 'Kraken XBT/USD trades'}
        for k, v in b.items():
            if v:
                w('| %s | %d | %.2f | %.2f | %s | %s | %s – %s |' % (names.get(k, k), v['windows'], v['meanLevel'], v['oneStepErrSd'], pct(100 * v['shareAbsErrOver10'], 2), pct(100 * v['shareAbsErrOver20'], 2), v['from'][:10], v['to'][:10]))
    open(a.out, 'w').write('\n'.join(L) + '\n')
    print('written', a.out, len(L), 'lines')


if __name__ == '__main__':
    main()
